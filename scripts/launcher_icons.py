"""Generate the launcher icon VectorDrawables.

Dreadnought and RHIB show the Blue Water mark, traced from blw.ai's 256 px app
icon; its coordinates below use that image's pixel grid. RHIB Control shows a
steering wheel. Run from the repository root:

    python3 scripts/launcher_icons.py [--preview preview.svg]

Colors come from each flavor's launcher_background/launcher_foreground values.
"""

import argparse
import math
from pathlib import Path


# Three stripes, each stepping up through the same S-curve. Stripe k is stripe 0
# moved down 54 px and left 14.55 px; only the lower bar's left end differs.
RIGHT = 227.5
LEFTS = (40.0, 25.6, 59.0)
HANDLE = 18.5
MARK_BOX = (25.6, 36.0, 227.5, 220.0)


def _solve(fraction):
    """Return t where a horizontal-handle cubic covers this fraction of its height."""
    lo, hi = 0.0, 1.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if 3 * mid * mid - 2 * mid ** 3 < fraction:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def _lerp(a, b, t):
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)


def _split(curve, t):
    a, b, c = (_lerp(curve[i], curve[i + 1], t) for i in range(3))
    d, e = _lerp(a, b, t), _lerp(b, c, t)
    f = _lerp(d, e, t)
    return [curve[0], a, d, f], [f, e, c, curve[3]]


def _stripe(k):
    top = 36 + 54 * k
    bottom = top + 76
    x0 = 166.4 - 14.55 * k
    x1 = 118.2 - 14.55 * k
    curve = [(x0, top), (x0 - HANDLE, top), (x1 + HANDLE, bottom), (x1, bottom)]
    # The upper bar spans top..top+39.5 and the lower bar top+36..bottom.
    upper, _ = _split(curve, _solve(36 / 76))
    _, lower = _split(curve, _solve(39.5 / 76))
    return [
        ("M", [curve[0]]), ("H", RIGHT), ("V", top + 39.5), ("H", lower[0][0]),
        ("C", lower[1:]), ("H", LEFTS[k]), ("V", top + 36), ("H", upper[3][0]),
        ("C", [upper[2], upper[1], upper[0]]), ("Z", None),
    ]


MARK = [_stripe(k) for k in range(3)]


def _number(value):
    text = ("%.2f" % value).rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def _path_data(commands, scale, dx, dy):
    x = lambda v: _number(v * scale + dx)
    y = lambda v: _number(v * scale + dy)
    out = []
    for command, args in commands:
        if command == "M":
            out.append("M" + x(args[0][0]) + "," + y(args[0][1]))
        elif command == "H":
            out.append("H" + x(args))
        elif command == "V":
            out.append("V" + y(args))
        elif command == "C":
            out.append("C" + " ".join(x(p[0]) + "," + y(p[1]) for p in args))
        else:
            out.append("Z")
    return "".join(out)


def mark_paths():
    """Return the Blue Water mark centered in a 108 x 108 viewport."""
    x0, y0, x1, y1 = MARK_BOX
    width, height = x1 - x0, y1 - y0
    scale = 64 / width
    dx = 54 - (x0 + width / 2) * scale
    dy = 54 - (y0 + height / 2) * scale
    return [_path_data(stripe, scale, dx, dy) for stripe in MARK]


# Holes wind opposite to their outlines because android:fillType needs API 24
# and minSdk is 23.
def _circle(radius, clockwise=True):
    sweep = 1 if clockwise else 0
    r = _number(radius)
    top, bottom = _number(54 - radius), _number(54 + radius)
    return f"M54,{top}A{r},{r} 0 1,{sweep} 54,{bottom}A{r},{r} 0 1,{sweep} 54,{top}Z"


def _spoke(degrees, length, width):
    angle = math.radians(degrees)
    ux, uy = math.cos(angle), math.sin(angle)
    px, py = -uy * width / 2, ux * width / 2
    corners = [(54 + px, 54 + py), (54 + ux * length + px, 54 + uy * length + py),
               (54 + ux * length - px, 54 + uy * length - py), (54 - px, 54 - py)]
    return "M" + "L".join(_number(cx) + "," + _number(cy) for cx, cy in corners) + "Z"


def wheel_paths():
    """Return a three-spoke steering wheel centered in a 108 x 108 viewport."""
    rim = _circle(32) + _circle(25, clockwise=False)
    spokes = [_spoke(degrees, 26, 7) for degrees in (180, 0, 90)]
    return [rim, _circle(9)] + spokes


def vector_drawable(paths):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by scripts/launcher_icons.py; edit that script instead. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp" android:height="108dp"',
        '    android:viewportWidth="108" android:viewportHeight="108">',
        '    <path android:fillColor="@color/launcher_background" android:pathData="M0,0h108v108h-108z" />',
    ]
    lines += [f'    <path android:fillColor="@color/launcher_foreground"\n        android:pathData="{d}" />'
              for d in paths]
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


ICONS = {
    # Dreadnought and RHIB share the mark; their colors differ by flavor.
    Path("app/src/main/res/drawable/ic_launcher.xml"): mark_paths,
    Path("app/src/rhibControl/res/drawable/ic_launcher.xml"): wheel_paths,
}


def preview(path):
    tiles = [("Dreadnought", "#3B72DF", mark_paths), ("RHIB", "#F9003C", mark_paths),
             ("RHIB Control", "#000000", wheel_paths)]
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" width="696" height="250" '
             'font-family="Helvetica, Arial, sans-serif">', '<rect width="696" height="250" fill="#1b1d20"/>']
    for i, (name, background, paths) in enumerate(tiles):
        x = 24 + i * 224
        body = f'<rect width="108" height="108" fill="{background}"/>' + "".join(
            f'<path fill="#FFFFFF" d="{d}"/>' for d in paths())
        parts.append(f'<svg x="{x}" y="24" width="192" height="192" viewBox="0 0 108 108">{body}</svg>')
        parts.append(f'<text x="{x + 96}" y="238" fill="#ffffff" font-size="16" text-anchor="middle">{name}</text>')
    parts.append("</svg>")
    Path(path).write_text("".join(parts) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preview", help="also write an SVG preview of all three icons")
    args = parser.parse_args()
    for target, paths in ICONS.items():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(vector_drawable(paths()))
    if args.preview:
        preview(args.preview)


if __name__ == "__main__":
    main()
